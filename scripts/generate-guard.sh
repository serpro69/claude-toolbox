#!/usr/bin/env bash
# Render every permission-guard projection from the canonical declaration.
# An optional output root supports freshness checks without editing the checkout.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
if [[ $# -gt 1 ]]; then
  echo "Usage: $0 [output-root]" >&2
  exit 1
fi
OUTPUT_ROOT="${1:-$REPO_ROOT}"
GUARD_SOURCE="$REPO_ROOT/klaude-plugin/scripts/guard"
RULES="$GUARD_SOURCE/guard-rules.json"
DOCS="docs/user-guide/configuration.md"
stage=$(mktemp -d "${TMPDIR:-/tmp}/generate-guard.XXXXXXXX")
trap 'rm -rf -- "$stage"' EXIT

# Refuse malformed declarations before replacing any generated destination.
jq -e '
  .version == 1 and
  (.secrets | type == "array" and all(.[]; type == "string" and test("^(\\./\\*\\*/|~/|//)"))) and
  (.destructive | type == "object" and all(.[]; type == "array")) and
  (.tmp_roots | type == "array") and (.selfmod | type == "array")
' "$RULES" >/dev/null

jq --slurpfile rules "$RULES" \
  '.permissions.deny = ($rules[0].secrets | unique | map("Read(" + . + ")"))' \
  "$REPO_ROOT/.claude/settings.json" >"$stage/settings.json"

{
  echo '# GENERATED by scripts/generate-guard.sh from klaude-plugin/scripts/guard/guard-rules.json — do not edit.'
  echo '# Only unconditional literals are projected; other destructive rules are enforced by the hook.'
  echo '# Native forbids override user exceptions and the hook temporary-cleanup exemption.'
  jq -r '
    .destructive[][] | . as $rule | .codex[]? |
    "\nprefix_rule(\n    pattern = " + (.pattern | tojson) +
    ",\n    decision = \"forbidden\",\n    justification = " + ($rule.reason | tojson) +
    ",\n    match = " + (.match | tojson) +
    ",\n    not_match = " + (.not_match | tojson) + ",\n)"
  ' "$RULES"
} >"$stage/default.rules"

jq -r '
  def cell: gsub("[\r\n]"; " ") | gsub("&"; "&amp;") | gsub("<"; "&lt;") | gsub(">"; "&gt;") | gsub("\\|"; "&#124;") | gsub("`"; "&#96;");
  def code: "`" + cell + "`";
  "### Secrets\n",
  "These globs generate the Claude settings deny list and apply in the guard. Add project globs in `.claude/kk-guard.json` under `secrets`; user exceptions never loosen secrets.\n",
  "| Scope | Glob |", "|-------|------|",
  (.secrets | sort[] | "| " + (if startswith("~/") then "Home" elif startswith("//") then "Absolute" else "Project" end) + " | " + code + " |"),
  "\n### Destructive commands\n",
  "Add rules in project config under `destructive`. User config at `~/.claude/kk-guard.json` can disable categories or exempt individual commands with `allow_patterns`. Native Codex forbids take precedence over those exceptions.\n",
  "| Category | Command | Denied operation | Codex forbid |",
  "|----------|---------|------------------|--------------|",
  (.destructive | to_entries[] | .key as $category | .value[] |
    "| " + ($category | cell) + " | " +
    (([.program] + (if .subcommand == null then [] elif (.subcommand | type) == "array" then .subcommand else [.subcommand] end) | join(" ")) | code) +
    " | " + (.reason | cell) + " | " + (if ((.codex // []) | length) > 0 then "Yes" else "No" end) + " |"),
  "\nThe hook exempts literal `rm` targets strictly beneath its temporary roots: " + (.tmp_roots | map(code) | join(", ")) + ". Secrets and protected configuration still apply. Codex native rules forbid `rm` even for temporary targets.\n",
  "### Protected configuration\n",
  "The guard blocks mutations of these paths, including moving their parent directories:\n",
  (.selfmod[] | "- " + code),
  "\nProject config may add paths under `selfmod`. To let an agent edit settings or guard files for one checkout, the user can add this entry to `~/.claude/kk-guard.json` (substitute the absolute project path):\n",
  "```json", "{\"version\":1,\"projects\":{\"/absolute/path/to/repo\":{\"disable_selfmod\":true}}}", "```",
  "\nThis exception does not allow reading or writing secrets."
' "$RULES" >"$stage/table.md"

# Replace only the marked block; missing/duplicate/reversed markers are errors.
awk -v block="$stage/table.md" '
  $0 == "<!-- BEGIN GUARD-RULES -->" {
    if (begins++ || ends) exit 1
    print
    while ((getline line < block) > 0) print line
    close(block)
    inside = 1
    next
  }
  $0 == "<!-- END GUARD-RULES -->" {
    if (!inside || ends++) exit 1
    inside = 0
    print
    next
  }
  !inside { print }
  END { if (begins != 1 || ends != 1 || inside) exit 1 }
' "$REPO_ROOT/$DOCS" >"$stage/configuration.md"

for file in guard.sh guard.py guard-rules.json LICENSE.md; do
  cp -p "$GUARD_SOURCE/$file" "$stage/$file"
done
mkdir -p "$OUTPUT_ROOT/.claude" "$OUTPUT_ROOT/.codex/rules" \
  "$OUTPUT_ROOT/.codex/scripts/guard" "$OUTPUT_ROOT/docs/user-guide"
cp "$stage/settings.json" "$OUTPUT_ROOT/.claude/settings.json"
cp "$stage/default.rules" "$OUTPUT_ROOT/.codex/rules/default.rules"
cp "$stage/configuration.md" "$OUTPUT_ROOT/$DOCS"
for file in guard.sh guard.py guard-rules.json LICENSE.md; do
  cp -p "$stage/$file" "$OUTPUT_ROOT/.codex/scripts/guard/$file"
done
